// Local fallback catalog, used only when Supabase env vars are missing or a
// fetch fails — keeps the storefront browsable for local development/demos
// without live credentials. Shape mirrors shapeItem() in watches.js.
const img = (id, alt) => ({
  id,
  url_externa: `https://images.unsplash.com/${id}?w=1400&q=80&auto=format&fit=crop`,
  alt_text: alt,
  sort_order: 0,
  is_cover: true,
});

function watch(id, title, status, attrs, image) {
  return {
    id,
    title,
    summary: attrs.short_description?.es || '',
    status,
    attrs,
    media: [image],
    coverUrl: image.url_externa,
    coverAlt: image.alt_text,
  };
}

